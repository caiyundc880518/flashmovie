/**
 * 生成一个中文名
 * @param rnd 返回 [0,1) 的随机函数
 */
export function generateName(rnd: () => number): string {
  const surname = SURNAMES[Math.floor(rnd() * SURNAMES.length)]
  const given = GIVEN[Math.floor(rnd() * GIVEN.length)]
  return surname + given
}
